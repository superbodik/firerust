pub fn has_noise_token(class: Option<&str>, id: Option<&str>) -> bool {
    [class, id].into_iter().flatten().any(|text| {
        text.split(|character: char| !character.is_alphanumeric())
            .any(|token| NOISE.contains(&token.to_ascii_lowercase().as_str()))
    })
}
