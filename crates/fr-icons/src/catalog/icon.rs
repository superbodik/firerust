#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Icon {
    ArrowLeft,
    ArrowRight,
    ArrowClockwise,
    Close,
    Plus,
    Star,
    StarFill,
    LockFill,
    UnlockFill,
    MenuDots,
    Bookmarks,
    BookmarkStar,
    Key,
    Gear,
    Download,
    Search,
    House,
    Globe,
    FileEarmark,
    ZoomIn,
    ZoomOut,
    MoonStars,
    Sun,
    InfoCircle,
    ExclamationTriangle,
    ShieldLock,
    Minimize,
    Maximize,
    Restore,
    Fire,
    ClockHistory,
    Terminal,
    Power,
}

impl Icon {
    pub const ALL: [Icon; 33] = [
        Self::ArrowLeft,
        Self::ArrowRight,
        Self::ArrowClockwise,
        Self::Close,
        Self::Plus,
        Self::Star,
        Self::StarFill,
        Self::LockFill,
        Self::UnlockFill,
        Self::MenuDots,
        Self::Bookmarks,
        Self::BookmarkStar,
        Self::Key,
        Self::Gear,
        Self::Download,
        Self::Search,
        Self::House,
        Self::Globe,
        Self::FileEarmark,
        Self::ZoomIn,
        Self::ZoomOut,
        Self::MoonStars,
        Self::Sun,
        Self::InfoCircle,
        Self::ExclamationTriangle,
        Self::ShieldLock,
        Self::Minimize,
        Self::Maximize,
        Self::Restore,
        Self::Fire,
        Self::ClockHistory,
        Self::Terminal,
        Self::Power,
    ];

    pub fn index(self) -> usize {
        Self::ALL.iter().position(|icon| *icon == self).unwrap_or(0)
    }

    pub fn svg(self) -> &'static str {
        match self {
            Self::ArrowLeft => include_str!("../../icons/arrow-left.svg"),
            Self::ArrowRight => include_str!("../../icons/arrow-right.svg"),
            Self::ArrowClockwise => include_str!("../../icons/arrow-clockwise.svg"),
            Self::Close => include_str!("../../icons/x-lg.svg"),
            Self::Plus => include_str!("../../icons/plus-lg.svg"),
            Self::Star => include_str!("../../icons/star.svg"),
            Self::StarFill => include_str!("../../icons/star-fill.svg"),
            Self::LockFill => include_str!("../../icons/lock-fill.svg"),
            Self::UnlockFill => include_str!("../../icons/unlock-fill.svg"),
            Self::MenuDots => include_str!("../../icons/three-dots-vertical.svg"),
            Self::Bookmarks => include_str!("../../icons/bookmarks.svg"),
            Self::BookmarkStar => include_str!("../../icons/bookmark-star.svg"),
            Self::Key => include_str!("../../icons/key.svg"),
            Self::Gear => include_str!("../../icons/gear.svg"),
            Self::Download => include_str!("../../icons/download.svg"),
            Self::Search => include_str!("../../icons/search.svg"),
            Self::House => include_str!("../../icons/house.svg"),
            Self::Globe => include_str!("../../icons/globe2.svg"),
            Self::FileEarmark => include_str!("../../icons/file-earmark.svg"),
            Self::ZoomIn => include_str!("../../icons/zoom-in.svg"),
            Self::ZoomOut => include_str!("../../icons/zoom-out.svg"),
            Self::MoonStars => include_str!("../../icons/moon-stars.svg"),
            Self::Sun => include_str!("../../icons/sun.svg"),
            Self::InfoCircle => include_str!("../../icons/info-circle.svg"),
            Self::ExclamationTriangle => include_str!("../../icons/exclamation-triangle.svg"),
            Self::ShieldLock => include_str!("../../icons/shield-lock.svg"),
            Self::Minimize => include_str!("../../icons/dash-lg.svg"),
            Self::Maximize => include_str!("../../icons/square.svg"),
            Self::Restore => include_str!("../../icons/window-stack.svg"),
            Self::Fire => include_str!("../../icons/fire.svg"),
            Self::ClockHistory => include_str!("../../icons/clock-history.svg"),
            Self::Terminal => include_str!("../../icons/terminal.svg"),
            Self::Power => include_str!("../../icons/power.svg"),
        }
    }
}
